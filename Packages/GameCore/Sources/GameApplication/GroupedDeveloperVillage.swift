    static let mapID = "river-clearing-review-64x48-v1"
    static func configuration(from base: GameConfiguration) throws -> GameConfiguration {
        var c = base
        c.map.id = mapID; c.map.width = 64; c.map.height = 48
        c.map.rows = terrainRows
        for (kind,width,height) in footprints {
            guard let i = c.buildings.firstIndex(where: { $0.kind == kind }) else { throw GameError.invalidConfiguration("Missing preview type") }
            c.buildings[i].width = width; c.buildings[i].height = height
        }
        try c.validate()
        return c
    }
    static func makeEngine(from base: GameConfiguration, now: Date) throws -> GameEngine {
        let c = try configuration(from: base)
        var g = try GameEngine(configuration: c, now: now)
        for t in c.technologyDefinitions { try g.developerUnlockTechnology(t.id) }
        g.developerRevealTerritory(radius: c.maximumExplorationRadius)
        g.developerFastConstruction = true
        for (kind,x,y) in placements {
            try Task.checkCancellation()
            g.developerAddResources(1_000_000)
            try g.build(kind, at: Tile(x: x,y: y))
            g.advance(to: g.state.lastUpdated.addingTimeInterval(3))
        }
        g.developerFastConstruction = false
        let roads = roadRuns.flatMap { x,end,y in (x...end).map { Tile(x: $0,y: y) } }
        try g.editRoads(at: roads, style: .trodden)
        // Stone and clay work sites are separate members of the quarry district.
        if let clay = g.state.buildings.last(where: { $0.kind == .stoneGatherer }) {
            try g.setProductionMode(buildingID: clay.id, recipeID: "clay")
        }
        g.developerAddPopulation(max(0,60-g.state.population))
        g.developerAddResources(1_000_000)
        g.developerRebaseClock(to: now)
        return try GameEngine(state: g.state, configuration: c)
    }
